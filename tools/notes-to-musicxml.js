#!/usr/bin/env node
/* ==========================================================================
 * tools/notes-to-musicxml.js — 把站内文字记谱导出成 MusicXML
 * --------------------------------------------------------------------------
 * 站内的谱例（练习、听辨、可视化图）都用文字记谱写在 content/units/ 里，
 * 例如 'C5:4 | D5:4 | E5:4'。文字记谱能算不能看，而"找错"这类练习不看谱
 * 就没法做，所以需要把它变成真五线谱：这个脚本 → MusicXML → MuseScore → SVG。
 *
 * 只取文字记谱里已经有的信息：音名（含临时记号，写法保留，不做等音改写）、
 * 时值（四分音符 = 1 拍）、小节线。调号恒为空，升降号写在音上。
 * 两个声部各自一行谱表，谱号由 --cfClef / --cpClef 给出（treble / bass / alto / tenor）。
 *
 * 用法（PowerShell 里记得用单引号，否则 | 会被当成管道）：
 *   node tools/notes-to-musicxml.js --id b1-spot-1 --title 'B1 找错练习 1' \
 *     --cf 'C5:4 | D5:4 | E5:4 | F5:4 | C5:4' \
 *     --cp 'F3:4 | G3:4 | A3:4 | Bb3:4 | C4:4' --cfClef treble --cpClef bass
 *
 * 输出：scores/<id>.musicxml
 *       然后跑 tools\build-scores.ps1 得到 assets/scores/<id>.svg + .mp3
 * ========================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
require(path.join(root, 'theory', 'core.js'));
require(path.join(root, 'theory', 'musicxml.js'));
const TH = globalThis.TH, MX = TH.musicxml;

const CLEFS = {
  treble: { sign: 'G', line: 2, octaveShift: 0 },
  bass: { sign: 'F', line: 4, octaveShift: 0 },
  alto: { sign: 'C', line: 3, octaveShift: 0 },
  tenor: { sign: 'C', line: 4, octaveShift: 0 },
  'treble-8': { sign: 'G', line: 2, octaveShift: -12 }
};

function usage() {
  console.log([
    '把站内文字记谱导出成 MusicXML。',
    '',
    '  node tools/notes-to-musicxml.js --id <文件名> --title <标题> \\',
    '       [--cf <记谱>] [--cp <记谱>] [--meter 4/4] \\',
    '       [--cfClef treble|bass|alto|tenor] [--cpClef ...] [--composer <名字>]',
    '',
    '记谱写法见 docs/记谱速查.md：C4:4 是全音符，:2 二分，:1 四分，R:2 是休止，"|" 是小节线。'
  ].join('\n'));
}

/** --flag value 形式的最小解析器 */
function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.indexOf('--') === 0) { out[a.slice(2)] = (argv[i + 1] !== undefined && argv[i + 1].indexOf('--') !== 0) ? argv[++i] : true; }
    else out._.push(a);
  }
  return out;
}

/** 站内文字记谱 → theory/musicxml.js 要的音符流 */
function notesFromText(text, who) {
  const sc = TH.makeScore({ cf: text || '', cp: '' });
  if (sc.warnings && sc.warnings.length) {
    sc.warnings.forEach(function (w) { console.warn('  ⚠ ' + who + '：' + w); });
  }
  return sc.cfE.map(function (e) {
    return {
      name: e.midi === null ? null : e.src.p.str,
      durQ: e.dur,
      rest: e.midi === null
    };
  });
}

function build(opts) {
  const meter = opts.meter || '4/4';
  const voices = [];
  if (opts.cf) voices.push({ name: 'CF', notes: notesFromText(opts.cf, 'CF'), clef: CLEFS[opts.cfClef] || CLEFS.treble });
  if (opts.cp) voices.push({ name: 'CP', notes: notesFromText(opts.cp, 'CP'), clef: CLEFS[opts.cpClef] || CLEFS.bass });
  if (!voices.length) throw new Error('至少要给 --cf 或 --cp 之一。');

  /* 谱表顺序按音高：谁高谁在上面，与谱号无关 */
  const parts = MX.orderByPitch(voices).map(function (o) { return o.it; });

  return MX.build({
    movementTitle: opts.title || opts.id || '',
    composer: opts.composer || undefined,
    rights: '本站自制谱例（content/units/）',
    software: 'tools/notes-to-musicxml.js',
    comment: 'Generated by tools/notes-to-musicxml.js from the site text notation',
    meter: meter,
    parts: parts
  });
}

function main() {
  const a = parseArgs(process.argv.slice(2));
  if (a.help || (!a.cf && !a.cp)) { usage(); process.exit(a.help ? 0 : 1); }
  const r = build(a);
  const outFile = a.out ? path.resolve(root, a.out) : path.join(root, 'scores', (a.id || 'score') + '.musicxml');
  fs.writeFileSync(outFile, r.xml, 'utf8');
  console.log('写出 ' + path.relative(root, outFile) + '　' + r.measureCount + ' 小节　' + r.barQ + ' 拍/小节');
  console.log('下一步：powershell -ExecutionPolicy Bypass -File tools\\build-scores.ps1');
}

if (require.main === module) main();
module.exports = { build: build, notesFromText: notesFromText, CLEFS: CLEFS };
